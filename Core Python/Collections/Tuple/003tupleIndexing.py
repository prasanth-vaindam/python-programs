this_tuple = ("apple", "banana", "cherry", "orange", "kiwi", "melon", "mango")
print(this_tuple[:4])  # By leaving out the start value, the range will start at the first item:
print(this_tuple[2:])  # By leaving out the end value, the range will go on to the end of the tuple:
print(this_tuple[-4:-1])
