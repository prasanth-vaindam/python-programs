"""
Program 3: Calculate Area of a Rectangle

Question:
Write a Python program to accept the length and breadth of a rectangle from the user.
Convert the inputs into integers and calculate the area.
"""

# Accept input
length = int(input("Enter length: "))
breadth = int(input("Enter breadth: "))

# Calculate area
area = length * breadth

# Display result
print("Area of Rectangle =", area)